-- Dedicated draft-only schema STORYOS_WEB_DRAFTS. Never execute in STORY_OS_RUNTIME.
CREATE TABLE IF NOT EXISTS WEB_DRAFT_WORKSPACE (
  WORKSPACE_ID CHAR(40) PRIMARY KEY,
  VERSION INT NOT NULL,
  BACKUP_JSON JSON NOT NULL,
  IDENTITY_MAP_JSON JSON NOT NULL,
  CREATE_TIME TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
  UPDATE_TIME TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS WEB_DRAFT_REQUEST (
  REQUEST_ID VARCHAR(100) PRIMARY KEY,
  PAYLOAD_SHA CHAR(64) NOT NULL,
  RESPONSE_JSON JSON NOT NULL
) ENGINE=InnoDB;
