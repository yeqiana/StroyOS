    enter.click();
    const canvas=await wait(()=>document.querySelector('[aria-label="分镜与素材创作画布"]'),'canvas');
    const directPin=await wait(()=>canvas.querySelector('button[aria-label="固定已批准 Frame 1 以对照"]'),'direct gallery pin');
    if(canvas.querySelectorAll('button[aria-label^="固定已批准 Frame"]').length<2)throw Error('insufficient pin actions');
