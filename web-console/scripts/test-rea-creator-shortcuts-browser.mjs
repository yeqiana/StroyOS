    if(!refs||!refs.textContent?.includes('人物')||!refs.textContent?.includes('视觉锚点'))throw Error('reference overview missing');
    refs.open=true;
    if(!refs.textContent?.includes('不代表素材已绑定此 Frame'))throw Error('reference provenance boundary missing');
